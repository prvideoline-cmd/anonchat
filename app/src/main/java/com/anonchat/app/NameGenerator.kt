package com.anonchat.app

import kotlin.random.Random

/**
 * Генератор тупых и смешных анонимных имён.
 * Новое имя выдаётся при каждом запуске приложения (при создании процесса)
 * и держится в памяти — при перезапуске приложения будет сгенерировано заново.
 */
object NameGenerator {

    // Иногда добавляем нелепый "титул" спереди для дополнительного угара.
    private val titles = listOf(
        "Капитан", "Товарищ", "Директор", "Профессор", "Магистр", "Барин",
        "Мэр", "Космонавт", "Шаман", "Атаман", "Верховный"
    )

    private val adjectives = listOf(
        "Бешеный", "Пьяный", "Лысый", "Голодный", "Сонный", "Пыльный",
        "Квадратный", "Внезапный", "Носатый", "Кривой", "Ленивый",
        "Подозрительный", "Мокрый", "Взрывной", "Молчаливый", "Наглый",
        "Угарный", "Задумчивый", "Плюшевый", "Ушастый", "Волосатый",
        "Загадочный", "Пузатый", "Скользкий", "Токсичный", "Диванный",
        "Одинокий", "Ржавый", "Простуженный", "Небритый"
    )

    private val nouns = listOf(
        "Пельмень", "Огурец", "Носок", "Баклажан", "Хомяк", "Бегемот",
        "Тапок", "Пирожок", "Утюг", "Веник", "Кактус", "Сосиска", "Гусь",
        "Чебурек", "Диван", "Холодильник", "Валенок", "Табурет", "Помидор",
        "Енот", "Сурок", "Кабанчик", "Осьминог", "Кальмар", "Бублик",
        "Штрудель", "Кефир", "Пингвин", "Барсук", "Тролль"
    )

    fun generate(): String {
        val useTitle = Random.nextInt(100) < 30 // с шансом ~30% добавляем титул
        val title = if (useTitle) titles.random() else ""
        val adjective = adjectives.random()
        val noun = nouns.random()
        val number = Random.nextInt(1, 999)
        return "$title$adjective$noun$number"
    }

    /** Цвет аватарки на основе имени, чтобы у каждого ника был стабильный "свой" цвет в рамках сессии. */
    fun colorSeed(name: String): Int {
        return name.hashCode()
    }
}
